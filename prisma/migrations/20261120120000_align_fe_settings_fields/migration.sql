-- Align persisted settings values with the FE contracts.
UPDATE "work_locations"
SET "state" = CASE UPPER("state")
  WHEN 'MY-01' THEN 'JOHOR'
  WHEN 'MY-02' THEN 'KEDAH'
  WHEN 'MY-03' THEN 'KELANTAN'
  WHEN 'MY-04' THEN 'MELAKA'
  WHEN 'MY-05' THEN 'NEGERI SEMBILAN'
  WHEN 'MY-06' THEN 'PAHANG'
  WHEN 'MY-07' THEN 'PENANG'
  WHEN 'MY-08' THEN 'PERAK'
  WHEN 'MY-09' THEN 'PERLIS'
  WHEN 'MY-10' THEN 'SELANGOR'
  WHEN 'MY-11' THEN 'TERENGGANU'
  WHEN 'MY-12' THEN 'SABAH'
  WHEN 'MY-13' THEN 'SARAWAK'
  WHEN 'MY-14' THEN 'KUALA LUMPUR'
  WHEN 'MY-15' THEN 'LABUAN'
  WHEN 'MY-16' THEN 'PUTRAJAYA'
  WHEN 'PULAU PINANG' THEN 'PENANG'
  WHEN 'MALACCA' THEN 'MELAKA'
  WHEN 'WILAYAH PERSEKUTUAN KUALA LUMPUR' THEN 'KUALA LUMPUR'
  ELSE UPPER("state")
END;

UPDATE "public_holidays"
SET "scope" = UPPER("scope");

ALTER TABLE "public_holidays"
ALTER COLUMN "scope" SET DEFAULT 'NATIONAL';

UPDATE "departments"
SET "status" = CASE WHEN "active" THEN 'ACTIVE' ELSE 'INACTIVE' END
WHERE "status" IS NULL OR UPPER("status") = 'DRAFT';

ALTER TABLE "positions" ALTER COLUMN "departmentId" DROP NOT NULL;
